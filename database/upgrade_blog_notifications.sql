USE obraforte_db;

CREATE TABLE IF NOT EXISTS blog_notification_preferences (
 user_id BIGINT NOT NULL PRIMARY KEY,
 email_enabled TINYINT(1) NOT NULL DEFAULT 0,
 push_enabled TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_blog_notification_user FOREIGN KEY(user_id) REFERENCES comment_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS blog_push_subscriptions (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT NOT NULL,
 endpoint_hash CHAR(64) NOT NULL UNIQUE,
 endpoint TEXT NOT NULL,
 p256dh VARCHAR(255) NOT NULL,
 auth_token VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_blog_push_user(user_id),
 CONSTRAINT fk_blog_push_user FOREIGN KEY(user_id) REFERENCES comment_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
